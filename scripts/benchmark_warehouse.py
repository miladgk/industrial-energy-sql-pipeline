"""
benchmark_warehouse.py
~~~~~~~~~~~~~~~~~~~~~~
Measure what the warehouse layout buys, on the real data, and write the result
to benchmarks/index_benchmark.md.

The same rows are queried in three layouts:
  1. flat table, no index           (a sequential scan of everything)
  2. flat table, primary key index  (dataset_id, start_time)
  3. fingrid_observation as built:  monthly partitions, each with that index

Query: one week of 1-minute grid frequency (dataset 177, the largest series),
the shape of every warehouse query (one dataset, one time range). Each layout
runs EXPLAIN (ANALYZE, BUFFERS) several times; the median execution time is kept.
Layouts 1 and 2 are temporary copies in a scratch schema, dropped afterwards.

Usage (needs a synced warehouse):
    python scripts/benchmark_warehouse.py
"""

import json
import os
import statistics
import sys
from datetime import datetime, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
from db_connection import get_connection  # noqa: E402

RUNS = 7
QUERY = ("SELECT count(*), min(value), avg(value) FROM {table} "
         "WHERE dataset_id = 177 AND start_time >= %(start)s AND start_time < %(end)s")
LAYOUTS = [
    ("Flat table, no index", "bench.flat_noindex"),
    ("Flat table, primary-key index (dataset_id, start_time)", "bench.flat_pk"),
    ("Monthly partitions, primary-key index (fingrid_observation)", "fingrid_observation"),
]


def _nodes(plan):
    yield plan
    for child in plan.get("Plans", []):
        yield from _nodes(child)


def _explain(cur, table, window):
    cur.execute("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + QUERY.format(table=table), window)
    root = cur.fetchone()[0][0]
    nodes = list(_nodes(root["Plan"]))
    return {
        "ms": root["Execution Time"],
        "relations": sorted({n["Relation Name"] for n in nodes if "Relation Name" in n}),
        "node_types": sorted({n["Node Type"] for n in nodes}),
        # per-loop average in EXPLAIN; a parallel scan has one loop per worker
        "rows_removed": sum(n.get("Rows Removed by Filter", 0) * n.get("Actual Loops", 1) for n in nodes),
        "buffers": sum(n.get("Shared Hit Blocks", 0) + n.get("Shared Read Blocks", 0) for n in nodes
                       if "Relation Name" in n or n["Node Type"].endswith("Index Scan")),
    }


def main() -> None:
    conn = get_connection()
    cur = conn.cursor()
    cur.execute("SELECT max(start_time) FROM fingrid_observation WHERE dataset_id = 177")
    newest = cur.fetchone()[0]
    if newest is None:
        sys.exit("No frequency data: run src/sync_fingrid.py first.")
    # A full week that ended at least a month ago, so it sits inside one older partition.
    months = newest.year * 12 + newest.month - 1 - 2                   # first day of the month two months back
    start = datetime(months // 12, months % 12 + 1, 1, tzinfo=timezone.utc)
    window = {"start": start, "end": start.replace(day=8)}

    cur.execute("SELECT count(*) FROM fingrid_observation")
    total_rows = cur.fetchone()[0]
    cur.execute("SELECT count(*) FROM pg_inherits WHERE inhparent = 'fingrid_observation'::regclass")
    partitions = cur.fetchone()[0]
    print(f"Building scratch copies of {total_rows:,} rows …")
    cur.execute("DROP SCHEMA IF EXISTS bench CASCADE; CREATE SCHEMA bench")
    cur.execute("CREATE TABLE bench.flat_noindex AS SELECT * FROM fingrid_observation")
    cur.execute("CREATE TABLE bench.flat_pk AS SELECT * FROM fingrid_observation")
    cur.execute("ALTER TABLE bench.flat_pk ADD PRIMARY KEY (dataset_id, start_time)")
    cur.execute("ANALYZE bench.flat_noindex; ANALYZE bench.flat_pk; ANALYZE fingrid_observation")
    conn.commit()

    results = []
    try:
        for label, table in LAYOUTS:
            _explain(cur, table, window)                       # warm the cache once
            runs = [_explain(cur, table, window) for _ in range(RUNS)]
            best = runs[0]
            results.append({"label": label, "table": table, "median_ms": statistics.median(r["ms"] for r in runs),
                            **{k: best[k] for k in ("relations", "node_types", "rows_removed", "buffers")}})
            print(f"  {label}: {results[-1]['median_ms']:.2f} ms")
        cur.execute("SELECT count(*) FROM fingrid_observation WHERE dataset_id = 177 "
                    "AND start_time >= %(start)s AND start_time < %(end)s", window)
        matched = cur.fetchone()[0]
    finally:
        conn.rollback()
        cur.execute("DROP SCHEMA IF EXISTS bench CASCADE")
        conn.commit()
        conn.close()

    base = results[0]["median_ms"]
    lines = [
        "# Warehouse layout benchmark",
        "",
        f"Generated by `scripts/benchmark_warehouse.py` on {datetime.now(timezone.utc):%Y-%m-%d} "
        f"(PostgreSQL in Docker, local machine; median of {RUNS} warm runs).",
        "",
        f"- Data: `fingrid_observation`, {total_rows:,} rows of real Fingrid data, {partitions} partitions "
        "(one per month plus a default).",
        f"- Query: one week of 1-minute grid frequency (dataset 177), {window['start']:%Y-%m-%d} to "
        f"{window['end']:%Y-%m-%d}, {matched:,} matching rows:",
        "",
        "```sql",
        QUERY.format(table="<layout>").replace("%(start)s", f"'{window['start']:%Y-%m-%d}'")
             .replace("%(end)s", f"'{window['end']:%Y-%m-%d}'"),
        "```",
        "",
        "| Layout | Median execution | vs. no index | Plan | Tables read | Rows read and discarded |",
        "|---|---:|---:|---|---|---:|",
    ]
    for r in results:
        lines.append(f"| {r['label']} | {r['median_ms']:.2f} ms | {base / r['median_ms']:.0f}x | "
                     f"{', '.join(r['node_types'])} | {', '.join(r['relations'])} | {r['rows_removed']:,} |")
    lines += [
        "",
        "Reading it:",
        "",
        "- Without an index PostgreSQL reads every row of every dataset and throws almost all of them away.",
        "- The primary-key index (dataset_id, start_time) is what makes the query fast: it jumps straight to "
        "the matching rows.",
        "- Partitioning adds pruning: the plan touches only the partition for that month, which keeps each "
        "index small as the table grows by about a million rows a year, and lets old months be dropped or "
        "archived as a whole. On a single lookup like this it is about as fast as the flat indexed table.",
        "",
        "Raw measurements:",
        "",
        "```json",
        json.dumps({"window": {k: v.isoformat() for k, v in window.items()}, "matched_rows": matched,
                    "total_rows": total_rows, "partitions": partitions, "results": results}, indent=2),
        "```",
        "",
    ]
    path = os.path.join(ROOT, "benchmarks", "index_benchmark.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"✓ wrote {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
